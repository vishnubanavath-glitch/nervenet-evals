"""Pin the eval environment to the exact package versions locked by the app.

Reads ../mcp-utilities/uv.lock (read-only, via `uv export --frozen`) and writes
those versions into this project's [tool.uv] constraint-dependencies, so the
code under test runs on the same library versions as the app itself.

    uv run python scripts/sync_app_pins.py          # rewrite pins
    uv run python scripts/sync_app_pins.py --check  # only report drift (exit 1 if any)

Run `uv sync` after rewriting.
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

EVALS_DIR = Path(__file__).resolve().parents[1]
APP_DIR = EVALS_DIR.parent / "mcp-utilities"
PYPROJECT = EVALS_DIR / "pyproject.toml"

# App pins that DeepEval cannot share. Only terminal/CLI helpers belong here:
# nothing the app runs while answering a question may be listed.
NOT_PINNED = {
    "rich",   # deepeval needs <15; only used by the mcp CLI for console output
    "click",  # deepeval needs <8.4; only used by the mcp CLI
}

START = "# >>> app pins (generated by scripts/sync_app_pins.py; do not edit by hand)"
END = "# <<< app pins"


def app_pins() -> list[str]:
    out = subprocess.run(
        ["uv", "export", "--frozen", "--no-hashes", "--no-header", "--no-emit-project"],
        cwd=APP_DIR, check=True, capture_output=True, text=True,
    ).stdout
    pins = set()
    for line in out.splitlines():
        line = line.split(";", 1)[0].strip()
        m = re.match(r"^([A-Za-z0-9_.\-]+)(\[[^\]]*\])?==(\S+)$", line)
        if m and m.group(1).lower() not in NOT_PINNED:
            pins.add(f"{m.group(1).lower()}=={m.group(3)}")
    return sorted(pins)


def render(pins: list[str]) -> str:
    body = "\n".join(f'    "{p}",' for p in pins)
    return f"{START}\nconstraint-dependencies = [\n{body}\n]\n{END}"


def main() -> int:
    pins = app_pins()
    text = PYPROJECT.read_text(encoding="utf-8")
    block = render(pins)
    if START in text:
        current = text[text.index(START): text.index(END) + len(END)]
    else:
        current = ""

    if "--check" in sys.argv:
        if current == block:
            print(f"OK: eval pins match the app lock ({len(pins)} packages).")
            return 0
        print("DRIFT: app lock changed. Run: uv run python scripts/sync_app_pins.py && uv sync")
        return 1

    if current:
        text = text.replace(current, block)
    else:
        text = text.replace("[tool.uv]\n", "[tool.uv]\n" + block + "\n", 1)
    PYPROJECT.write_text(text, encoding="utf-8")
    print(f"Wrote {len(pins)} app pins to pyproject.toml. Now run: uv sync")
    return 0


if __name__ == "__main__":
    sys.exit(main())
